// Assembles frontend sources into Apps Script pages and static GitHub Pages output.
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const FE = path.join(ROOT, 'frontend'), OUT = path.join(ROOT, 'google-apps-script'), PAGES = path.join(ROOT, 'docs');
const read = f => fs.readFileSync(path.join(FE, f), 'utf8');
fs.mkdirSync(PAGES, { recursive: true });
for (const page of ['home', 'admin', 'scanner', 'verify']) {
  let t = read(page + '.html');
  t = t.replace(/<!--@css (\S+)-->/g, (m, f) => '<style>\n' + read(f) + '\n</style>');
  t = t.replace(/<!--@js (\S+)-->/g, (m, f) => {
    const js = read(f);
    if (js.includes('</script>') || js.includes('<?')) throw new Error(f + ' contains </script> or <? which breaks Apps Script templates');
    return '<script>\n' + js + '\n</script>';
  });
  const name = page[0].toUpperCase() + page.slice(1) + '.html';
  fs.writeFileSync(path.join(OUT, name), '<!-- GENERATED by scripts/build.js from frontend/' + page + '.html. Edit files in frontend/, then run: npm run build -->\n' + t);
  const staticHtml = t
    .replace(/href="\?page=admin"/g, 'href="admin.html"')
    .replace(/href="\?page=scanner"/g, 'href="scanner.html"')
    .replace(/href="\?"/g, 'href="index.html"');
  if (staticHtml.includes('<?')) throw new Error(page + '.html contains an Apps Script template tag that cannot be published on GitHub Pages.');
  fs.writeFileSync(path.join(PAGES, page === 'home' ? 'index.html' : page + '.html'),
    '<!-- GENERATED by scripts/build.js from frontend/' + page + '.html. Edit files in frontend/, then run: npm run build -->\n' + staticHtml);
  console.log('built', name, 'and docs/' + (page === 'home' ? 'index' : page) + '.html');
}
